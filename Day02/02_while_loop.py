# Day 02 - While Loop

# Example 1: Print numbers from 1 to 5

count = 1

while count <= 5:
    print(count)
    count += 1


# Example 2: Countdown

number = 5

while number > 0:
    print("Countdown:", number)
    number -= 1

print("Done!")


