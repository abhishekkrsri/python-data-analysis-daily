# Day 02 - For Loop

# Example 1: Print numbers from 1 to 5
for i in range(1, 6):
    print(i)

# Example 2: Loop through trading symbols
symbols = ["EURUSD", "GBPUSD", "XAUUSD"]

for symbol in symbols:
    print("Symbol:", symbol)

# Exercise: Print even numbers from 2 to 10
for number in range(2, 11, 2):
    print(number)