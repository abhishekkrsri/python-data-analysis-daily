# Integer
age = 22

# Float
height = 5.9

# String
name = "Abhishek"

# Boolean
is_student = True

# List
skills = ["Python", "SQL", "Pandas"]

# Tuple
marks = (80, 85, 90)

# Dictionary
student = {
    "name": "Abhishek",
    "age": 22
}

print(type(age))
print(type(height))
print(type(name))
print(type(is_student))
print(type(skills))
print(type(marks))
print(type(student))